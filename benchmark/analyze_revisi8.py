def load_and_merge_eval_files(paths: Iterable[Path]) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    merged_map: Dict[Tuple[str, str, str], Dict[str, Any]] = {}
    cat_shas = set()
    eval_shas = set()
    git_commits = set()
    hyperparams_list = []
    input_files = []

    for p in paths:
        input_files.append(p.name)
        data = json.loads(p.read_text(encoding="utf-8"))
        prov = data.get("provenance") or {}
        if prov.get("catalogSnapshotSha256"):
            cat_shas.add(prov["catalogSnapshotSha256"])
        if prov.get("evaluatorSha256"):
            eval_shas.add(prov["evaluatorSha256"])
        if prov.get("gitCommit"):
            git_commits.add(prov["gitCommit"])
        if prov.get("hyperparams"):
            hyperparams_list.append(prov["hyperparams"])

        for rec in data.get("records", []):
            key = (rec["caseId"], rec["requestedModel"], rec["config"])
            merged_map[key] = rec

    if len(cat_shas) > 1 or len(eval_shas) > 1:
        print(
            f"WARNING: Merged eval files have differing provenance hashes! catalog={cat_shas}, evaluator={eval_shas}",
            file=sys.stderr,
        )

    provenance = {
        "input_files": input_files,
        "git_commits": sorted(git_commits),
        "catalog_shas": sorted(cat_shas),
        "evaluator_shas": sorted(eval_shas),
        "hyperparams": hyperparams_list[0] if hyperparams_list else {},
    }
    return list(merged_map.values()), provenance


def build_analysis(records: List[Dict[str, Any]], provenance: Dict[str, Any], seed: int = 42) -> Dict[str, Any]:
    models = sorted({r["requestedModel"] for r in records})
    present_cfgs_set = {r["config"] for r in records}
    configs_present = [c for c in CONFIG_ORDER if c in present_cfgs_set] + sorted(
        present_cfgs_set - set(CONFIG_ORDER)
    )

    overall: Dict[str, Dict[str, Any]] = {}
    by_language: Dict[str, Dict[str, Dict[str, Any]]] = {}
    by_category: Dict[str, Dict[str, Dict[str, Any]]] = {}

    for m in models:
        overall[m] = {}
        by_language[m] = {}
        by_category[m] = {}
        for cfg in configs_present:
            grp = [r for r in records if r["requestedModel"] == m and r["config"] == cfg]
            if not grp:
                continue
            overall[m][cfg] = summarize_group(grp, m)

            by_language[m][cfg] = {}
            for lang in LANGUAGE_ORDER:
                sub = [r for r in grp if r.get("language") == lang]
                if sub:
                    by_language[m][cfg][lang] = summarize_group(sub, m)

            by_category[m][cfg] = {}
            for cat in CATEGORY_ORDER:
                sub = [r for r in grp if r.get("category") == cat]
                if sub:
                    by_category[m][cfg][cat] = summarize_group(sub, m)

    paired_comparisons: List[Dict[str, Any]] = []
    target_metrics = ["csr", "faithfulness", "refusal", "financialAccuracy"]

    # Within-model architectural & ablation pairs
    arch_pairs = [
        ("proposed_hybrid", "full_context"),
        ("proposed_hybrid", "zero_shot"),
        ("full_context", "zero_shot"),
        ("plus_prefilter", "full_context"),
        ("plus_calculator", "plus_prefilter"),
        ("proposed_hybrid", "plus_calculator"),
    ]
    for m in models:
        for cfg_a, cfg_b in arch_pairs:
            recs_a = [r for r in records if r["requestedModel"] == m and r["config"] == cfg_a]
            recs_b = [r for r in records if r["requestedModel"] == m and r["config"] == cfg_b]
            if not recs_a or not recs_b:
                continue
            for mk in target_metrics:
                paired_comparisons.append(
                    compare_record_sets(f"[{m}] {cfg_a} vs {cfg_b}", recs_a, recs_b, mk, seed=seed)
                )

    # Cross-model paired comparisons within identical architecture
    if len(models) == 2:
        m_a, m_b = models[0], models[1]
        for cfg in configs_present:
            recs_a = [r for r in records if r["requestedModel"] == m_a and r["config"] == cfg]
            recs_b = [r for r in records if r["requestedModel"] == m_b and r["config"] == cfg]
            if not recs_a or not recs_b:
                continue
            for mk in target_metrics:
                paired_comparisons.append(
                    compare_record_sets(f"[{cfg}] {m_a} vs {m_b}", recs_a, recs_b, mk, seed=seed)
                )

    return {
        "schemaVersion": "revisi8-analysis-v1",
        "provenance": provenance,
        "models": models,
        "configs_present": configs_present,
        "overall": overall,
        "by_language": by_language,
        "by_category": by_category,
        "paired_comparisons": paired_comparisons,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Analyze Revisi 8 benchmark evaluation JSON files.")
    parser.add_argument("eval_files", nargs="+", help="One or more eval_*.json files")
    parser.add_argument("--out-json", dest="out_json", help="Path to write structured JSON report")
    parser.add_argument("--out-md", dest="out_md", help="Path to write Markdown report")
    parser.add_argument("--seed", type=int, default=42, help="Bootstrap/permutation PRNG seed (default: 42)")
    args = parser.parse_args()

    paths = [Path(p) for p in args.eval_files]
    for p in paths:
        if not p.exists():
            print(f"Error: File not found: {p}", file=sys.stderr)
            return 1

    records, provenance = load_and_merge_eval_files(paths)
    report = build_analysis(records, provenance, seed=args.seed)
    md = render_markdown(report)

    print(md)

    if args.out_json:
        out_j = Path(args.out_json)
        out_j.parent.mkdir(parents=True, exist_ok=True)
        out_j.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"Analysis JSON written to: {out_j}")

    if args.out_md:
        out_m = Path(args.out_md)
        out_m.parent.mkdir(parents=True, exist_ok=True)
        out_m.write_text(md, encoding="utf-8")
        print(f"Analysis Markdown written to: {out_m}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())

