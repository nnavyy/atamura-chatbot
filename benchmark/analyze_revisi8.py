def compare_record_sets(
    label: str,
    records_a: List[Dict[str, Any]],
    records_b: List[Dict[str, Any]],
    metric_key: str,
    seed: int = 42,
) -> Dict[str, Any]:
    map_a = {r["caseId"]: r for r in records_a}
    map_b = {r["caseId"]: r for r in records_b}
    common_ids = sorted(set(map_a.keys()) & set(map_b.keys()))

    a_bin: List[int] = []
    b_bin: List[int] = []
    excluded_infra = 0
    excluded_na = 0
    scenario_buckets_a: Dict[str, List[int]] = defaultdict(list)
    scenario_buckets_b: Dict[str, List[int]] = defaultdict(list)
    scenario_expected_counts: Dict[str, int] = defaultdict(int)

    for cid in common_ids:
        ra = map_a[cid]
        rb = map_b[cid]
        scen_id = ra.get("semanticScenarioId") or cid.rsplit("-", 1)[0]
        scenario_expected_counts[scen_id] += 1

        if ra.get("status") != "ok" or ra.get("infraError") or not ra.get("eval"):
            excluded_infra += 1
            continue
        if rb.get("status") != "ok" or rb.get("infraError") or not rb.get("eval"):
            excluded_infra += 1
            continue

        va = ra["eval"].get(metric_key)
        vb = rb["eval"].get(metric_key)
        if va is None or vb is None:
            excluded_na += 1
            continue

        pa = 1 if va >= 100 else 0
        pb = 1 if vb >= 100 else 0
        a_bin.append(pa)
        b_bin.append(pb)
        scenario_buckets_a[scen_id].append(pa)
        scenario_buckets_b[scen_id].append(pb)

    query_mcnemar = exact_mcnemar_test(a_bin, b_bin)

    # Cluster-level aggregation over independent semanticScenarioId clusters
    scen_ids = sorted(scenario_buckets_a.keys())
    scen_strict_a: List[int] = []
    scen_strict_b: List[int] = []
    scen_complete3_strict_a: List[int] = []
    scen_complete3_strict_b: List[int] = []
    scen_deltas: List[float] = []
    incomplete_clusters = 0

    for sid in scen_ids:
        vals_a = scenario_buckets_a[sid]
        vals_b = scenario_buckets_b[sid]
        strict_a = 1 if all(x == 1 for x in vals_a) else 0
        strict_b = 1 if all(x == 1 for x in vals_b) else 0
        scen_strict_a.append(strict_a)
        scen_strict_b.append(strict_b)

        if len(vals_a) >= 3 and len(vals_b) >= 3:
            scen_complete3_strict_a.append(strict_a)
            scen_complete3_strict_b.append(strict_b)
        else:
            incomplete_clusters += 1

        mean_a = sum(vals_a) / len(vals_a)
        mean_b = sum(vals_b) / len(vals_b)
        scen_deltas.append(mean_a - mean_b)

    cluster_mcnemar = exact_mcnemar_test(scen_strict_a, scen_strict_b)
    cluster_complete3_mcnemar = (
        exact_mcnemar_test(scen_complete3_strict_a, scen_complete3_strict_b)
        if scen_complete3_strict_a
        else None
    )
    boot_lo, boot_hi = paired_cluster_bootstrap_ci(scen_deltas, n_boot=10000, seed=seed)
    perm_p = paired_cluster_permutation_p(scen_deltas, n_perm=20000, seed=seed)

    return {
        "comparison": label,
        "metric": metric_key,
        "common_case_ids": len(common_ids),
        "excluded_due_to_infra": excluded_infra,
        "excluded_due_to_na": excluded_na,
        "query_level": query_mcnemar,
        "cluster_level": {
            "n_clusters": len(scen_ids),
            "incomplete_clusters_lt3_langs": incomplete_clusters,
            "strict_all_langs_mcnemar": cluster_mcnemar,
            "strict_complete3_only_mcnemar": cluster_complete3_mcnemar,
            "mean_cluster_delta_pp": round(statistics.mean(scen_deltas) * 100.0, 2) if scen_deltas else None,
            "cluster_bootstrap_95ci_pp": [boot_lo, boot_hi],
            "cluster_signflip_perm_p": perm_p,
        },
    }


