def _log_binom_pmf(i: int, n: int, p: float) -> float:
    if p <= 0.0:
        return 0.0 if i == 0 else float("-inf")
    if p >= 1.0:
        return 0.0 if i == n else float("-inf")
    log_c = math.lgamma(n + 1) - math.lgamma(i + 1) - math.lgamma(n - i + 1)
    return log_c + i * math.log(p) + (n - i) * math.log1p(-p)


def binom_cdf_le(k: int, n: int, p: float) -> float:
    """P(X <= k) for X ~ Binomial(n, p)."""
    if k < 0:
        return 0.0
    if k >= n:
        return 1.0
    if p <= 0.0:
        return 1.0
    if p >= 1.0:
        return 0.0
    total = 0.0
    for i in range(0, k + 1):
        lp = _log_binom_pmf(i, n, p)
        if lp > -745.0:
            total += math.exp(lp)
    return min(1.0, max(0.0, total))


def binom_sf_ge(k: int, n: int, p: float) -> float:
    """P(X >= k) for X ~ Binomial(n, p)."""
    if k <= 0:
        return 1.0
    if k > n:
        return 0.0
    if p <= 0.0:
        return 0.0
    if p >= 1.0:
        return 1.0
    total = 0.0
    for i in range(k, n + 1):
        lp = _log_binom_pmf(i, n, p)
        if lp > -745.0:
            total += math.exp(lp)
    return min(1.0, max(0.0, total))


def clopper_pearson_ci(k: int, n: int, alpha: float = 0.05) -> Tuple[Optional[float], Optional[float]]:
    """Exact two-sided (1 - alpha) Clopper-Pearson binomial confidence interval."""
    if n <= 0:
        return None, None
    half_alpha = alpha / 2.0

    if k <= 0:
        lower = 0.0
    else:
        lo, hi = 0.0, k / n
        for _ in range(90):
            mid = 0.5 * (lo + hi)
            if binom_sf_ge(k, n, mid) < half_alpha:
                lo = mid
            else:
                hi = mid
        lower = 0.5 * (lo + hi)

    if k >= n:
        upper = 1.0
    else:
        lo, hi = k / n, 1.0
        for _ in range(90):
            mid = 0.5 * (lo + hi)
            if binom_cdf_le(k, n, mid) < half_alpha:
                hi = mid
            else:
                lo = mid
        upper = 0.5 * (lo + hi)

    return round(lower * 100.0, 2), round(upper * 100.0, 2)


def exact_mcnemar_test(a_outcomes: List[int], b_outcomes: List[int]) -> Dict[str, Any]:
    """Exact two-sided binomial McNemar test on matched 0/1 outcomes."""
    n = len(a_outcomes)
    if n == 0 or n != len(b_outcomes):
        return {
            "n_pairs": 0,
            "a_rate": None,
            "b_rate": None,
            "delta_pp": None,
            "b_pass_fail": 0,
            "c_fail_pass": 0,
            "discordant": 0,
            "p_value": None,
        }

    a_sum = sum(a_outcomes)
    b_sum = sum(b_outcomes)
    b_only = sum(1 for a, b in zip(a_outcomes, b_outcomes) if a == 1 and b == 0)
    c_only = sum(1 for a, b in zip(a_outcomes, b_outcomes) if a == 0 and b == 1)
    n_disc = b_only + c_only

    if n_disc == 0:
        p_val = 1.0
    else:
        m = min(b_only, c_only)
        p_val = min(1.0, 2.0 * binom_cdf_le(m, n_disc, 0.5))

    return {
        "n_pairs": n,
        "a_pass": a_sum,
        "b_pass": b_sum,
        "a_rate": round((a_sum / n) * 100.0, 2),
        "b_rate": round((b_sum / n) * 100.0, 2),
        "delta_pp": round(((a_sum - b_sum) / n) * 100.0, 2),
        "b_pass_fail": b_only,
        "c_fail_pass": c_only,
        "discordant": n_disc,
        "p_value": p_val,
    }


def paired_cluster_bootstrap_ci(
    deltas: List[float], n_boot: int = 10000, seed: int = 42, alpha: float = 0.05
) -> Tuple[Optional[float], Optional[float]]:
    """Nonparametric cluster bootstrap 95% CI over per-scenario mean differences."""
    n = len(deltas)
    if n == 0:
        return None, None
    if n == 1:
        val = round(deltas[0] * 100.0, 2)
        return val, val
    rng = random.Random(seed)
    means: List[float] = []
    for _ in range(n_boot):
        s = 0.0
        for _j in range(n):
            s += deltas[rng.randrange(n)]
        means.append(s / n)
    means.sort()
    lo_idx = max(0, int(math.floor((alpha / 2.0) * (n_boot - 1))))
    hi_idx = min(n_boot - 1, int(math.ceil((1.0 - alpha / 2.0) * (n_boot - 1))))
    return round(means[lo_idx] * 100.0, 2), round(means[hi_idx] * 100.0, 2)


def paired_cluster_permutation_p(
    deltas: List[float], n_perm: int = 20000, seed: int = 42
) -> Optional[float]:
    """Two-sided paired sign-flip permutation p-value over cluster mean differences."""
    n = len(deltas)
    if n == 0:
        return None
    non_zero = [d for d in deltas if abs(d) > 1e-12]
    if not non_zero:
        return 1.0
    obs = abs(sum(deltas))
    k = len(non_zero)
    if k <= 16:
        # Exact enumeration of all 2^k sign flips
        total = 1 << k
        extreme = 0
        for mask in range(total):
            s = 0.0
            for idx, val in enumerate(non_zero):
                s += val if (mask & (1 << idx)) else -val
            if abs(s) >= obs - 1e-12:
                extreme += 1
        return extreme / total

    rng = random.Random(seed)
    extreme = 0
    for _ in range(n_perm):
        s = 0.0
        for val in non_zero:
            s += val if rng.getrandbits(1) else -val
        if abs(s) >= obs - 1e-12:
            extreme += 1
    return (extreme + 1) / (n_perm + 1)


def percentile_nearest_rank(values: List[float], q: float) -> Optional[float]:
    if not values:
        return None
    sorted_vals = sorted(values)
    idx = max(0, min(len(sorted_vals) - 1, math.ceil((q / 100.0) * len(sorted_vals)) - 1))
    return sorted_vals[idx]


