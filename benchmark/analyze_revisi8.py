def metric_stats(records: List[Dict[str, Any]], extractor: Callable[[Dict[str, Any]], Optional[int]]) -> Dict[str, Any]:
    valid_vals = []
    for r in records:
        if r.get("status") != "ok" or r.get("infraError") or not r.get("eval"):
            continue
        v = extractor(r)
        if v is not None:
            valid_vals.append(1 if v >= 100 else 0)
    n = len(valid_vals)
    k = sum(valid_vals)
    ci_lo, ci_hi = clopper_pearson_ci(k, n)
    return {
        "k": k,
        "n": n,
        "rate": round((k / n) * 100.0, 2) if n > 0 else None,
        "ci95_low": ci_lo,
        "ci95_high": ci_hi,
    }


def summarize_group(records: List[Dict[str, Any]], model: str) -> Dict[str, Any]:
    valid = [r for r in records if r.get("status") == "ok" and not r.get("infraError") and r.get("eval")]
    infra = [r for r in records if r.get("status") != "ok" or r.get("infraError") or not r.get("eval")]

    infra_by_type: Dict[str, int] = defaultdict(int)
    for r in infra:
        err_key = f"{r.get('statusCode', '?')}:{r.get('errorType') or 'unknown'}"
        infra_by_type[err_key] += 1

    api_lats = [float(r["apiLatencyMs"]) for r in valid if r.get("apiLatencyMs") is not None]
    pipe_lats = [float(r["pipelineLatencyMs"]) for r in valid if r.get("pipelineLatencyMs") is not None]

    prompt_toks = [int((r.get("usage") or {}).get("prompt_tokens") or 0) for r in valid]
    comp_toks = [int((r.get("usage") or {}).get("completion_tokens") or 0) for r in valid]
    reason_toks = [int((r.get("usage") or {}).get("reasoning_tokens") or 0) for r in valid]
    length_trunc = sum(1 for r in valid if r.get("finishReason") == "length")
    sanitized_count = sum(1 for r in valid if r.get("sanitized") is True)
    fallback_leaked = sum(1 for r in valid if r.get("usedFallback") is True)

    sum_prompt = sum(prompt_toks)
    sum_comp = sum(comp_toks)
    in_price, out_price = MODEL_PRICING_PER_1M.get(model, (0.0, 0.0))
    est_cost_usd = round((sum_prompt / 1_000_000.0) * in_price + (sum_comp / 1_000_000.0) * out_price, 6)

    return {
        "total_records": len(records),
        "valid_ok": len(valid),
        "infra_errors": len(infra),
        "infra_breakdown": dict(infra_by_type),
        "sanitized_count": sanitized_count,
        "fallback_leaked": fallback_leaked,
        "finish_reason_length": length_trunc,
        "metrics": {
            "csr": metric_stats(valid, lambda r: r["eval"].get("csr")),
            "faithfulness": metric_stats(valid, lambda r: r["eval"].get("faithfulness")),
            "refusal": metric_stats(valid, lambda r: r["eval"].get("refusal")),
            "financialAccuracy": metric_stats(valid, lambda r: r["eval"].get("financialAccuracy")),
            "financialTextAccuracy": metric_stats(valid, lambda r: r["eval"].get("financialTextAccuracy")),
            "financialJsonAccuracy": metric_stats(valid, lambda r: r["eval"].get("financialJsonAccuracy")),
            "financialConsistency": metric_stats(valid, lambda r: r["eval"].get("financialConsistency")),
        },
        "latency": {
            "api_mean_ms": round(statistics.mean(api_lats), 1) if api_lats else None,
            "api_median_ms": round(statistics.median(api_lats), 1) if api_lats else None,
            "api_p95_ms": round(percentile_nearest_rank(api_lats, 95) or 0.0, 1) if api_lats else None,
            "pipeline_mean_ms": round(statistics.mean(pipe_lats), 1) if pipe_lats else None,
            "pipeline_median_ms": round(statistics.median(pipe_lats), 1) if pipe_lats else None,
            "pipeline_p95_ms": round(percentile_nearest_rank(pipe_lats, 95) or 0.0, 1) if pipe_lats else None,
        },
        "tokens": {
            "prompt_total": sum_prompt,
            "completion_total": sum_comp,
            "reasoning_total": sum(reason_toks),
            "prompt_mean": round(statistics.mean(prompt_toks), 1) if prompt_toks else None,
            "completion_mean": round(statistics.mean(comp_toks), 1) if comp_toks else None,
            "reasoning_mean": round(statistics.mean(reason_toks), 1) if reason_toks else None,
            "estimated_cost_usd": est_cost_usd,
        },
    }


