def fmt_metric(m: Dict[str, Any]) -> str:
    if m["n"] == 0 or m["rate"] is None:
        return "N/A"
    return f"{m['rate']:.1f}% ({m['k']}/{m['n']}, 95% CI [{m['ci95_low']:.1f}, {m['ci95_high']:.1f}])"


def fmt_metric_short(m: Dict[str, Any]) -> str:
    if m["n"] == 0 or m["rate"] is None:
        return "N/A"
    return f"{m['rate']:.1f}% ({m['k']}/{m['n']})"


def fmt_p(p: Optional[float]) -> str:
    if p is None:
        return "N/A"
    if p < 0.0001:
        return f"{p:.2e} (<0.0001)"
    return f"{p:.4f}"


