    lines.append("")

    # Paired Hypothesis Tests (Query-level & Scenario-Cluster level)
    lines.append("## 6. Paired Hypothesis Tests (Exact McNemar & Cluster-Aware Inference)")
    lines.append(
        "> **Methodological Note (P0.5):** Each semantic scenario (`n=40`) is instantiated in 3 languages (`EN/RU/KK` -> `n=120` queries). "
        "Query-level McNemar reports discordant counts over all matched queries, while **Scenario-Cluster tests (`n=40` independent `semanticScenarioId` clusters)** "
        "eliminate intra-scenario language correlation via (a) strict all-languages-pass McNemar and (b) 10,000-resample cluster bootstrap 95% CI + paired sign-flip permutation p-value."
    )
    lines.append("")
    lines.append(
        "| Model / Pair | Metric | Query McNemar (`n`, b/c, delta, p) | Strict Cluster McNemar (`n_clust`, b/c, delta, p) | Cluster Mean Delta (95% Boot CI) & Perm p |"
    )
    lines.append("|---|---|---|---|---|")
    for c in report["paired_comparisons"]:
        q = c["query_level"]
        cl = c["cluster_level"]
        cm = cl["strict_all_langs_mcnemar"]
        q_str = (
            f"n={q['n_pairs']}, ({q['b_pass_fail']}/{q['c_fail_pass']}), "
            f"{q['delta_pp']:+.1f} pp, p={fmt_p(q['p_value'])}"
            if q["n_pairs"] > 0
            else "N/A"
        )
        cm_str = (
            f"n={cm['n_pairs']}, ({cm['b_pass_fail']}/{cm['c_fail_pass']}), "
            f"{cm['delta_pp']:+.1f} pp, p={fmt_p(cm['p_value'])}"
            if cm["n_pairs"] > 0
            else "N/A"
        )
        ci = cl["cluster_bootstrap_95ci_pp"]
        boot_str = (
            f"{cl['mean_cluster_delta_pp']:+.1f} pp [{ci[0]:+.1f}, {ci[1]:+.1f}], perm p={fmt_p(cl['cluster_signflip_perm_p'])}"
            if cl["mean_cluster_delta_pp"] is not None
            else "N/A"
        )
        lines.append(f"| {c['comparison']} | `{c['metric']}` | {q_str} | {cm_str} | {boot_str} |")
    lines.append("")

    return "\n".join(lines)


